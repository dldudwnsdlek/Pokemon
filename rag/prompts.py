RETRY_JSON = "\n\n앞의 답은 형식이 틀렸다. JSON 배열만 다시 출력해."


def parse_json_array(text: str):
    """응답에서 처음 나오는 [ 부터 마지막 ] 까지만 잘라 json.loads 한다. 실패하면 None."""
    start, end = text.find("["), text.rfind("]")
    if start == -1 or end <= start:
        return None
    try:
        value = json.loads(text[start:end + 1])
    except json.JSONDecodeError:
        # 끝에 쉼표가 붙은 흔한 실수만 한 번 고쳐 본다
        try:
            value = json.loads(re.sub(r",\s*]", "]", text[start:end + 1]))
        except json.JSONDecodeError:
            return None
    return value if isinstance(value, list) else None


def ask_json_array(prompt: str, ask) -> list | None:
    """JSON 배열을 받는다. 실패하면 한 번만 다시 요청하고, 그래도 실패하면 None."""
    first = ask(prompt)
    value = parse_json_array(first)
    if value is None:
        value = parse_json_array(ask(prompt + "\n\n[앞의 답]\n" + first + RETRY_JSON))
    return value
